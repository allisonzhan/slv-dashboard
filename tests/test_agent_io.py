def test_snapshot_file_schema_if_present():
    if not snapshot.PATH.exists():
        return  # generated by `python -m slv_dashboard.snapshot`; not available in CI
    s = json.loads(snapshot.PATH.read_text(encoding="utf-8"))
    assert set(snapshot.REQUIRED_KEYS) <= set(s)
    assert s["schema_version"] == snapshot.SCHEMA_VERSION
