def test_tagger_buckets_and_word_boundaries():
    t = news.tag("Iran war lifts gold and silver as Fed holds rates")
    assert {"geopolitics", "fed_rates"} <= set(t["buckets"].split(",")) and t["silver"]
    assert news.tag("Software firm warns of slowdown")["buckets"] == ""      # no 'war' in 'software'/'warns'
    assert "solar" in news.tag("Solar panel makers cut silver loadings")["buckets"]


def test_parse_and_build_dedupes_drops_old_and_irrelevant():
    rows = news.parse_rss(RSS, "google:silver")
    assert rows[0]["source"] == "Reuters" and rows[0]["title"].startswith("Silver jumps")
    df = news.build(rows, now=pd.Timestamp("2026-10-26 18:00"))
    assert len(df) == 2                                   # duplicate, old and irrelevant items gone
    assert df.iloc[0]["title"].startswith("Peru") or df.iloc[0]["relevance"] >= df.iloc[1]["relevance"]
    top = news.top_by_bucket(df)
    assert top["supply_mines"][0]["title"].startswith("Peru")


def test_clean_makes_json_safe():
    out = snapshot._clean({"a": np.float64("nan"), "b": np.int64(3), "c": pd.Timestamp("2026-10-26"),
                           "d": [np.bool_(True), 1.23456789]})
    assert out == {"a": None, "b": 3, "c": "2026-10-26", "d": [True, 1.234568]}
    json.dumps(out)


