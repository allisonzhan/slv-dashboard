def test_brief_has_agent_blocks_and_numbers():
    md = export.render_markdown(_fake_snapshot())
    names = [m.group(1) for m in export.AGENT_RE.finditer(md)]
    assert names == ["bottom_line", "news", "talking_points"]
    assert "54.05" in md and "No edge" in md and "FOMC decision" in md
    html = export.render_html(md, [])
    assert "<table>" in html and "AGENT" not in html


